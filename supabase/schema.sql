CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Table des utilisateurs (synchronisée avec Firebase Auth)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(150) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    is_staff BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Table des Chefs de projet
CREATE TABLE IF NOT EXISTS public.chefs_de_projet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    specialite VARCHAR(255) NOT NULL DEFAULT '',
    email VARCHAR(255) NOT NULL UNIQUE,
    max_creneaux_entretien INTEGER NOT NULL DEFAULT 30,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_chefs_nom ON public.chefs_de_projet(nom);

-- Table des Étudiants
CREATE TABLE IF NOT EXISTS public.etudiants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    adresse_email VARCHAR(255) NOT NULL UNIQUE,
    parcours VARCHAR(20) NOT NULL DEFAULT 'I2026',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_etudiants_email ON public.etudiants(adresse_email);

-- Table des Sélections / Vœux
CREATE TABLE IF NOT EXISTS public.selections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etudiant_id BIGINT NOT NULL REFERENCES public.etudiants(id) ON DELETE CASCADE,
    chef_de_projet_id BIGINT NOT NULL REFERENCES public.chefs_de_projet(id) ON DELETE CASCADE,
    priorite INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_selection_etudiant_chef UNIQUE(etudiant_id, chef_de_projet_id)
);

