-- Table des Rendez-vous validés
CREATE TABLE IF NOT EXISTS public.rendez_vous (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    heure TIME NOT NULL,
    heure_fin TIME NOT NULL,
    chef_de_projet_id BIGINT NOT NULL REFERENCES public.chefs_de_projet(id) ON DELETE CASCADE,
    etudiant_id BIGINT NOT NULL REFERENCES public.etudiants(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_rdv_chef_creneau UNIQUE(chef_de_projet_id, date, heure),
    CONSTRAINT uq_rdv_etudiant_creneau UNIQUE(etudiant_id, date, heure)
);

-- Table des Évaluations (notes A, B, C, D)
CREATE TABLE IF NOT EXISTS public.evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chef_de_projet_id BIGINT NOT NULL REFERENCES public.chefs_de_projet(id) ON DELETE CASCADE,
    etudiant_id BIGINT NOT NULL REFERENCES public.etudiants(id) ON DELETE CASCADE,
    note VARCHAR(5) NOT NULL,
    commentaire TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_eval_chef_etudiant UNIQUE(chef_de_projet_id, etudiant_id)
);

-- Table des Affectations finales
CREATE TABLE IF NOT EXISTS public.affectation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chef_de_projet_id BIGINT NOT NULL REFERENCES public.chefs_de_projet(id) ON DELETE CASCADE,
    etudiant_id BIGINT NOT NULL UNIQUE REFERENCES public.etudiants(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Configuration RLS (Row Level Security)
