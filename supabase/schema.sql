ALTER TABLE public.evaluations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.affectation ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
    t text;
    tables_list text[] := ARRAY[
        'users', 'chefs_de_projet', 'etudiants', 'selections',
        'disponibilite_binaire_chefprojet', 'disponibilite_binaire_etudiant',
        'rendez_vous', 'evaluations', 'affectation'
    ];
BEGIN
    FOREACH t IN ARRAY tables_list LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Public access" ON public.%I', t);
        EXECUTE format('CREATE POLICY "Public access" ON public.%I FOR ALL USING (true) WITH CHECK (true)', t);
    END LOOP;
END $$;
